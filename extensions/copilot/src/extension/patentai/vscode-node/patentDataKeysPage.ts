/** Presence-only view state — the ONLY key-related data that ever reaches the webview. */
export interface DataKeysPageState {
	readonly epoConfigured: boolean;
	readonly usptoConfigured: boolean;
}

/** Messages the webview posts to the extension. */
type PageInMessage =
	| { readonly type: 'ready' }
	| { readonly type: 'saveEpo'; readonly key: string; readonly secret: string }
	| { readonly type: 'saveUspto'; readonly key: string }
	| { readonly type: 'test'; readonly provider: Provider }
	| { readonly type: 'clear'; readonly provider: Provider }
	| { readonly type: 'openSignup'; readonly provider: Provider }
	| { readonly type: 'openModelPicker' }
	| { readonly type: 'openPreferences' }
	| { readonly type: 'accountSignIn' }
	| { readonly type: 'accountSignOut' }
	| { readonly type: 'accountManageSubscription' }
	| { readonly type: 'setOcrConsent'; readonly verdict: string };

/** Register the `flowleap.patentDataKeys` command: reveals the FlowLeap Settings sidebar. An
 *  optional provider argument (e.g. from the Setup view or the invalid-key toast) focuses
 *  that provider's section. */
export function registerPatentDataKeysCommand(viewProvider: PatentDataKeysViewProvider, logService: ILogService): vscode.Disposable {
	return vscode.commands.registerCommand(PATENT_DATA_KEYS_COMMAND, async (provider?: Provider) => {
		try {
			await viewProvider.reveal(provider === 'epo' || provider === 'uspto' ? provider : undefined);
		} catch (error) {
			logService.error(`[Patent AI] FlowLeap Settings view failed: ${error instanceof Error ? error.message : String(error)}`);
		}
	});
}

/**
 * On startup, reveal the FlowLeap Settings sidebar for users who have not set anything up
 * yet (no patent-data keys, no FlowLeap session, no BYOK model) so the first-run path is
 * "open app → sidebar is already on Settings → add keys". Opt-out via the
 * `flowleap.showSetupOnStartup` setting; configured users are never interrupted.
 */
export async function maybeShowSetupOnStartup(store: PatentDataKeysStore, authProvider: FlowLeapAuthenticationProvider, logService: ILogService): Promise<void> {
	if (!vscode.workspace.getConfiguration().get<boolean>(SHOW_SETUP_ON_STARTUP_SETTING, true)) {
		return;
	}
	await store.whenReady;
	const keys = store.getKeys();
	if (keys?.epo || keys?.usptoOdp) {
		return;
	}
	try {
		const sessions = await authProvider.getSessions();
		if (sessions.length > 0) {
			return;
		}
	} catch {
		// Unreadable session state — treat as signed out and keep evaluating.
	}
	try {
		const models = await vscode.lm.selectChatModels({});
		if (models.some(m => !NON_BYOK_VENDORS.has(m.vendor))) {
			return;
		}
	} catch {
		// Model enumeration unavailable this early — a fresh install has none anyway.
	}
	if (!(await canFocusSettingsView())) {
		return;
	}
	logService.info('[Patent AI] First-run setup incomplete — revealing the FlowLeap Settings sidebar');
	await vscode.commands.executeCommand(SETTINGS_VIEW_FOCUS_COMMAND);
}

/** The "FlowLeap Settings" webview view in its own activity-bar container. */
export class PatentDataKeysViewProvider implements vscode.WebviewViewProvider {

	private _view: vscode.WebviewView | undefined;
	private _pendingFocus: Provider | undefined;
	private readonly _disposables: vscode.Disposable[] = [];

	constructor(
		private readonly _store: PatentDataKeysStore,
		private readonly _client: IPatentBackendClient,
		private readonly _authProvider: FlowLeapAuthenticationProvider,
		private readonly _logService: ILogService,
		private readonly _ocrConsentService: IOcrConsentService,
	) { }

	register(): vscode.Disposable {
		this._disposables.push(
			vscode.window.registerWebviewViewProvider(SETTINGS_VIEW_ID, this, { webviewOptions: { retainContextWhenHidden: true } }),
			// Keep the badges live if keys change elsewhere (e.g. the store's initial async load).
			this._store.onDidChange(() => this._postState()),
			// Keep the Account section live across sign-in/out and the late profile-fetch `{changed}`.
			this._authProvider.onDidChangeSessions(() => void this._postAccountState()),
			// Keep the Privacy row live: a verdict answered at the OCR prompt must show up here
			// without the user reopening the view.
			this._ocrConsentService.onDidChangeVerdict(() => this._postOcrConsent()),
		);
		return vscode.Disposable.from(...this._disposables);
	}

	/** Reveal the settings sidebar, optionally scrolling to one provider's card. */
	async reveal(focus?: Provider): Promise<void> {
		if (!(await canFocusSettingsView())) {
			this._logService.info('[Patent AI] FlowLeap Settings view is not available in this window');
			return;
		}
		if (focus) {
			this._pendingFocus = focus;
		}
		await vscode.commands.executeCommand(SETTINGS_VIEW_FOCUS_COMMAND);
		if (this._view && focus) {
			this._pendingFocus = undefined;
			this._post({ type: 'focus', provider: focus });
		}
	}

	resolveWebviewView(webviewView: vscode.WebviewView): void {
		this._view = webviewView;
		// No localResourceRoots: everything is inlined, the view loads no resources at all.
		webviewView.webview.options = { enableScripts: true, localResourceRoots: [] };
		webviewView.webview.html = renderPatentDataKeysPageHtml(getNonce());
		webviewView.onDidDispose(() => {
			this._view = undefined;
		}, null, this._disposables);
		webviewView.webview.onDidReceiveMessage((message: PageInMessage) => this._onMessage(message), null, this._disposables);
	}

	private _post(message: object): void {
		void this._view?.webview.postMessage(message);
	}

	private _postState(focus?: Provider): void {
		const keys = this._store.getKeys();
		const state: DataKeysPageState = { epoConfigured: !!keys?.epo, usptoConfigured: !!keys?.usptoOdp };
		this._post({ type: 'state', ...state, focus });
	}

	/** Reflect the current OCR consent verdict; the service owns it, the page only shows it. */
	private _postOcrConsent(): void {
		this._post({ type: 'ocrConsent', verdict: this._ocrConsentService.getVerdict() ?? 'ask' });
	}

	private _postStatus(provider: Provider, kind: 'testing' | 'ok' | 'error' | 'warn' | 'info', message: string): void {
		this._post({ type: 'status', provider, kind, message });
	}

	/**
	 * Compute and post the Account section state (identity + subscription pill). Reads only data the
	 * auth provider already fetches; the pure {@link computeAccountState} owns the mapping so the view
	 * stays a reflector. Signed-out short-circuits without a subscription fetch.
	 */
	private async _postAccountState(): Promise<void> {
		const identity = this._authProvider.getIdentity();
		const snapshot = identity ? await this._authProvider.getSubscriptionSnapshot() : { status: 'unknown' as const };
		const state = computeAccountState(identity, snapshot, Date.now());
		this._post({ type: 'account', ...state });
	}

	/**
	 * Open the user's Stripe billing portal in the browser. Fetches the URL through the backend-client
	 * seam (inheriting its typed 401/402 errors) and surfaces a friendly toast on failure so the button
	 * never appears broken.
	 */
	private async _openCustomerPortal(): Promise<void> {
		try {
			const portalUrl = await this._client.getCustomerPortalUrl(CancellationToken.None);
			await vscode.env.openExternal(vscode.Uri.parse(portalUrl));
		} catch (error) {
			this._logService.error(`[Patent AI] Manage subscription failed: ${error instanceof Error ? error.message : String(error)}`);
			void vscode.window.showErrorMessage('Could not open the FlowLeap subscription portal. Please try again in a moment.');
		}
	}

	private async _onMessage(message: PageInMessage): Promise<void> {
		try {
			switch (message.type) {
				case 'ready': {
					const focus = this._pendingFocus;
					this._pendingFocus = undefined;
					this._postState(focus);
					this._postOcrConsent();
					void this._postAccountState();
					return;
				}
				case 'setOcrConsent': {
					// 'ask' clears back to undecided; anything else must be a verdict.
					const verdict = message.verdict === 'always' || message.verdict === 'never' ? message.verdict : undefined;
					await this._ocrConsentService.setVerdict(verdict);
					return;
				}
				case 'saveEpo': {
					const key = message.key.trim();
					const secret = message.secret.trim();
					if (!key || !secret) {
						this._postStatus('epo', 'error', 'Enter both the consumer key and the consumer secret.');
						return;
					}
					await this._store.setEpoCredentials({ key, secret });
					await this._afterSave('epo');
					return;
				}
				case 'saveUspto': {
					const key = message.key.trim();
					if (!key) {
						this._postStatus('uspto', 'error', 'Enter the API key.');
						return;
					}
					await this._store.setUsptoOdpKey(key);
					await this._afterSave('uspto');
					return;
				}
				case 'test':
					await this._runTest(message.provider);
					return;
				case 'clear':
					// Confirmation is the view's two-step Clear button — no native dialog here.
					await this._store.clearProvider(message.provider);
					this._postStatus(message.provider, 'info', 'Removed from secure storage.');
					return;
				case 'openSignup': {
					const spec = PROVIDERS.find(s => s.provider === message.provider)!;
					await vscode.env.openExternal(vscode.Uri.parse(spec.signupUrl));
					return;
				}
				case 'openModelPicker':
					await vscode.commands.executeCommand('workbench.action.chat.manage');
					return;
				case 'openPreferences':
					await vscode.commands.executeCommand('workbench.action.openSettings', '@flowleap');
					return;
				case 'accountSignIn':
					// The canonical user-facing sign-in command owned by the FlowLeap auth provider.
					await vscode.commands.executeCommand('flowleap.signIn');
					return;
				case 'accountSignOut':
					await vscode.commands.executeCommand('patent-ai.signOut');
					return;
				case 'accountManageSubscription':
					await this._openCustomerPortal();
					return;
			}
		} catch (error) {
			this._logService.error(`[Patent AI] FlowLeap Settings view action failed: ${error instanceof Error ? error.message : String(error)}`);
		}
	}

	/** Save persisted — confirm, then auto-test so a typo is caught now, not mid-research. */
	private async _afterSave(provider: Provider): Promise<void> {
		this._postStatus(provider, 'info', 'Saved to secure storage.');
		await this._runTest(provider);
	}

	private async _runTest(provider: Provider): Promise<void> {
		this._postStatus(provider, 'testing', 'Testing connection…');
		const result = await testPatentDataConnection(this._client, provider);
		if (result.ok) {
			this._postStatus(provider, 'ok', result.message);
			return;
		}
		if (result.failedProvider && result.failedProvider !== provider) {
			// The OTHER provider's stored key blocked this test — flag its section too.
			this._postStatus(result.failedProvider, 'error', result.message);
			this._postStatus(provider, 'warn', 'Could not complete the test — fix the flagged key first.');
			return;
		}
		// A rejection is an error; signed-out / unreachable is a warning (the key was still saved).
		this._postStatus(provider, result.failedProvider ? 'error' : 'warn', result.message);
	}
}

